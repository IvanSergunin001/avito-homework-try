// Идемпотентность оформления заказа. Ключ здесь — сам идентификатор заказа, который
// выдаёт клиент: отдельной таблицы ключей у площадки нет.
//
// Таблица ключей понадобилась бы, если бы ключ жил отдельно от того, что им защищено, —
// и тогда её пришлось бы чистить, а заказ и его ключ могли бы разъехаться. Здесь
// защищаемое и ключ — одно и то же значение: первичный ключ заказа. Повтор отбивается
// уникальностью самой строки, а не проверкой «нет ли уже такого» перед вставкой — между
// проверкой и вставкой помещается второе нажатие «Заказать», и обе попытки прошли бы
// проверку.
//
// Отличить повтор от переиспользования ключа умеет только отпечаток запроса: тот же
// идентификатор с другим составом — это не «тот же заказ», а сломанный клиент, и молча
// отдать ему чужой по смыслу заказ означало бы подтвердить покупку, которой он не делал.

package domain

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"slices"
	"strconv"
	"strings"

	"github.com/google/uuid"
)

// Repeat отвечает на повторное оформление заказа, который у площадки уже есть: тем же
// заказом, если запрос повторили дословно, и отказом, если тем же идентификатором
// оформляют что-то другое.
//
// Второй заказ не заводится ни в одном из случаев — ни когда повтор настоящий, ни когда
// клиент переиспользовал ключ: идентификатор занят, и занят он навсегда.
func (o Order) Repeat(placed Order) (Order, error) {
	switch {
	// Порядок проверок — часть правила: чужой заказ отбивается до сверки состава, иначе
	// по разным ответам «ключ переиспользован» и «повтор принят» перебор идентификаторов
	// рассказал бы, что заказывают другие покупатели.
	case o.CustomerID != placed.CustomerID:
		return Order{}, ErrOrderIDTaken
	case o.RequestHash != placed.RequestHash:
		return Order{}, ErrIdempotencyKeyReuse
	}

	return o, nil
}

// ProductOf отвечает, какой товар площадки заведение назвало своим идентификатором.
//
// Отвечает по составу заказа, а не по каталогу: заказ уехал заведению снимком, и
// позиция, из-за которой заведение отказало, — это позиция снимка, даже если в каталоге
// её к этому моменту уже нет. Товара, о котором заказ не знает, здесь нет: заведение
// назвало позицию, которой ему не передавали, и показывать покупателю нечего.
func (o Order) ProductOf(externalID string) uuid.UUID {
	for _, item := range o.Items {
		if item.ExternalID == externalID {
			return item.ProductID
		}
	}

	return uuid.Nil
}

// requestHash — отпечаток запроса, которым оформлен заказ: заведение, адрес доставки и
// состав корзины.
//
// В отпечаток входит только то, что прислал клиент. Цен в нём нет намеренно: цену
// подставляет площадка из своего каталога, и тот же самый запрос, повторённый после
// подорожания, — это тот же запрос, а не другой; иначе повтор по таймауту упирался бы в
// «ключ переиспользован» всякий раз, когда заведение поменяло ценник.
//
// Порядок позиций в отпечатке не участвует: корзина — это набор, а не список, и заказ,
// переставленный клиентом местами, остаётся тем же заказом. Одна и та же позиция дважды
// в состав не попадает (её отбивает totalOf), поэтому набор строк однозначен.
//
// Хеш, а не сам запрос: отпечаток лежит рядом с заказом в базе, и хранить в нём копию
// корзины значило бы держать состав заказа дважды — а расходиться две копии начали бы с
// первой же правки формата хранения.
func requestHash(restaurantID uuid.UUID, address string, items []OrderItem) string {
	lines := make([]string, 0, len(items))
	for _, item := range items {
		lines = append(lines, item.ProductID.String()+":"+strconv.Itoa(item.Quantity))
	}
	slices.Sort(lines)

	// Разделитель между полями — перевод строки, которого нет ни в идентификаторе, ни в
	// количестве: без него адрес, кончающийся цифрой, склеился бы с составом, и два
	// разных заказа получили бы один отпечаток.
	sum := sha256.Sum256([]byte(restaurantID.String() + "\n" + address + "\n" + strings.Join(lines, "\n")))

	return hex.EncodeToString(sum[:])
}

// ErrIdempotencyKeyReuse — тем же идентификатором заказа оформляют другой заказ.
//
// Это ошибка клиента, а не отказ предметной области: идентификатор заказа он же и
// выдаёт, и переиспользовать его под другую корзину означает потерять один из двух
// заказов. Ответ на неё — не «попробуйте ещё раз», а «выдайте новый идентификатор».
var ErrIdempotencyKeyReuse = errors.New("idempotency key reuse")

// ErrOrderIDTaken — идентификатор заказа принадлежит другому покупателю.
//
// Что именно за ним стоит, наружу не сообщается: по разным ответам перебор
// идентификаторов рассказал бы, какие заказы на площадке есть и чем они отличаются от
// присланного. Покупателю остаётся одно и то же действие — оформить заказ заново.
var ErrOrderIDTaken = errors.New("order id belongs to another customer")
