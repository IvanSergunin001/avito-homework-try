// Журнал состояний заказа: во что заказ переходил, по чьему требованию и когда.
//
// Журнал ведёт сам агрегат, а не тот, кто его вызвал. Записанное вызывающей стороной
// попадало бы в журнал только там, где о нём вспомнили, — и первая же ветка, где о нём
// забыли, оставила бы заказ с историей, в которой состояния меняются сами собой. Здесь
// запись делает единственный метод, которым состояние вообще меняется, поэтому «каждое
// изменение записано» — это свойство кода, а не договорённость между обработчиками.
//
// Зачем журнал нужен: статус в самом заказе отвечает только на вопрос «что с ним сейчас».
// Разбор жалобы «заказ отменили без предупреждения» и вопрос «долго ли заведение думало
// над заказом» задаются к истории, которой в одной колонке нет. Восстановить её задним
// числом неоткуда — переход не оставляет следов, кроме того, который оставлен здесь.

package domain

import (
	"slices"
	"time"
)

// StatusEvent — одно изменение состояния заказа.
type StatusEvent struct {
	// Status — состояние, в которое заказ перешёл.
	Status OrderStatus
	// Actor — по чьему требованию переход выполнен.
	Actor Actor
	// OccurredAt — когда площадка его выполнила.
	//
	// По часам площадки, даже когда о переходе сообщило заведение: часы двух организаций
	// не сверены, и журнал, собранный из двух источников времени, перестал бы отвечать
	// на единственный вопрос, ради которого он и ведётся, — что за чем случилось.
	OccurredAt time.Time
}

// StatusChanges — переходы, случившиеся с заказом здесь и сейчас: их предстоит записать
// в журнал вместе с самим заказом.
//
// Прочитанный из хранилища заказ их не несёт, и это не потеря: его переходы записаны
// тогда, когда случились, а записанные второй раз они удвоили бы историю.
func (o Order) StatusChanges() []StatusEvent {
	return slices.Clone(o.changes)
}

// Recorded отдаёт заказ, переходы которого уже записаны в журнал: дальше в журнал попадёт
// только то, что случится с заказом после записи.
//
// Копией, а не правкой на месте: заказ уезжает в хранилище значением, и «записано» — это
// то, что о заказе отвечает хранилище, а не то, что заказ думает о себе сам. Без этого
// ответа второе сохранение того же заказа записало бы его историю дважды.
func (o Order) Recorded() Order {
	o.changes = nil

	return o
}

// record запоминает переход. Зовётся только оттуда, где состояние действительно
// изменилось, — и потому в журнал попадает каждое изменение, а не то, о котором
// вспомнили.
func (o *Order) record(status OrderStatus, by Actor, at time.Time) {
	o.changes = append(o.changes, StatusEvent{Status: status, Actor: by, OccurredAt: at})
}
