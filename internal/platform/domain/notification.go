// Уведомления заведения о смене статуса заказа.
//
// После того как заведение взялось за заказ, двигают его только уведомления: площадка
// статусы не опрашивает — инициатива у той стороны, которая знает, что происходит с
// заказом на кухне. Опрос дал бы то же самое ценой постоянного стука во все подключённые
// заведения и всё равно с задержкой в интервал опроса.
//
// Доставка уведомлений ненадёжна: заведение повторяет их, пока не получит ответ, — и
// повторы приезжают вперемешку с новыми. Поэтому приём обязан быть идемпотентным, и
// делает его таким не проверка «а не приходило ли уже такое», а порядок самих состояний:
// заказ движется по пути в одну сторону, и уведомление о состоянии, которое он уже
// прошёл, ничего не меняет — сколько бы раз оно ни приехало.
//
// Отдельной таблицы принятых уведомлений здесь нет по той же причине, по какой у
// оформления нет таблицы ключей идемпотентности: защита уже есть в самом состоянии
// заказа, а вторая её копия рядом только разъезжалась бы с первой.

package domain

import (
	"slices"
	"time"
)

// progression — путь заказа от оформления до доставки в том порядке, в каком заказ его
// проходит.
//
// Отмены в этом списке нет, и это не пропуск: отмена не ступень пути, а его обрыв, и
// вопрос «раньше или позже готовки» у неё смысла не имеет — отменить можно и заказ,
// который только что оформили, и тот, который вот-вот повезут.
var progression = []OrderStatus{Pending, UnderReview, Confirmed, Cooking, Delivering, Completed}

// ApplyNotification применяет уведомление заведения о том, что заказ продвинулся, и
// отвечает, изменилось ли от него состояние заказа.
//
// «Не изменилось» — это не отказ: уведомление принято, и повторять его заведению не
// нужно. Так отвечает площадка на две ситуации, в которых менять нечего:
//
//   - заказ уже прожил свою жизнь (`completed`, `cancelled`) — из терминального
//     состояния его не двигает никто, и опоздавшее «готовим» не воскрешает доставленный
//     заказ;
//   - заказ уже прошёл состояние, о котором сообщают, — это ретрай или обогнавшее его
//     уведомление, и возвращать заказ назад значило бы показать покупателю «готовим»
//     после «везём».
//
// Всё остальное — настоящий переход, и разрешает его матрица, а не этот метод: заведение,
// уведомившее о доставке заказа, который ещё не начали везти, получает отказ по тому же
// правилу, по которому его получил бы кто угодно другой.
func (o *Order) ApplyNotification(status OrderStatus, reason string, at time.Time) (bool, error) {
	if o.Status.IsTerminal() || o.passed(status) {
		return false, nil
	}

	// Отмена — не просто переход: заведение обязано назвать причину, её увидит
	// покупатель. Спрашивает её то же самое правило отмены, что и у саппорта.
	if status == Cancelled {
		if err := o.Cancel(ByRestaurant, reason, at); err != nil {
			return false, err
		}

		return true, nil
	}

	if err := o.TransitionTo(status, ByRestaurant, at); err != nil {
		return false, err
	}

	return true, nil
}

// passed отвечает, прошёл ли заказ состояние status.
//
// Состояния сравниваются местом на пути заказа, а не временем, которое проставило
// заведение: часы двух организаций не сверены, и уведомление, отправленное отставшими
// часами, оказалось бы «старее» того, что случилось раньше него. Место на пути от часов
// не зависит.
func (o Order) passed(status OrderStatus) bool {
	notified := slices.Index(progression, status)
	if notified < 0 {
		// Отмены на пути нет: пройденной она не бывает, и решает её судьбу матрица.
		return false
	}

	return slices.Index(progression, o.Status) >= notified
}
