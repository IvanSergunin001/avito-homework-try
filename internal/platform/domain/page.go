package domain

import (
	"errors"
	"fmt"
)

// Page — окно выдачи: сколько записей пропустить и сколько отдать. Окно доменное, а не
// транспортное: границы страницы — это правило площадки («не больше сотни за раз»), а не
// подробность HTTP, и потолок площадка держит независимо от того, кто её спрашивает.
type Page struct {
	// Limit — сколько записей отдавать на страницу.
	Limit int
	// Offset — сколько записей пропустить от начала выдачи.
	Offset int
}

// NewPage собирает окно выдачи: отсутствующие границы заменяет умолчаниями, выходящие за
// объявленные контрактом — отклоняет.
//
// Проверка живёт здесь, а не в спецификации: кодогенератор разбирает параметры, но не
// сверяет их с `minimum` и `maximum`. Отдать страницу больше объявленной в контракте
// нельзя — клиент вправе рассчитывать на потолок, а служба на предсказуемый объём выдачи.
//
// Умолчание и потолок приходят снаружи: их объявляет контракт поверхности, и у витрины
// покупателя они одни, а у соседних поверхностей будут свои.
func NewPage(limit, offset *int, defaultLimit, maxLimit int) (Page, error) {
	page := Page{Limit: defaultLimit}

	if limit != nil {
		page.Limit = *limit
	}
	if page.Limit < 1 || page.Limit > maxLimit {
		return Page{}, fmt.Errorf("limit: допустимы значения от 1 до %d", maxLimit)
	}

	if offset != nil {
		page.Offset = *offset
	}
	if page.Offset < 0 {
		return Page{}, errors.New("offset: допустимы значения не меньше 0")
	}

	return page, nil
}
