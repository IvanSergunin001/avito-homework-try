package domain

import (
	"errors"

	"github.com/google/uuid"
)

// Money — сумма в минорных единицах валюты, то есть в копейках. Отдельный тип, а не
// просто число: единица измерения видна в подписи и не теряется при передаче, а сложить
// копейки с количеством штук по недосмотру нельзя.
//
// Целое, а не число с плавающей точкой: `0.1 + 0.2` в двоичной дроби не равно `0.3`, и
// деньги, посчитанные так, расходятся с чеком.
type Money int64

// Product — позиция меню заведения, как её видит покупатель: что он покупает, почём и
// можно ли это заказать прямо сейчас.
//
// Реквизиты синхронизации каталога (внешний идентификатор в системе заведения, время
// обновления) сюда не относятся: витрина о них не рассказывает.
type Product struct {
	// ID — идентификатор товара на площадке, по которому открывается его карточка.
	ID uuid.UUID
	// RestaurantID — заведение, которому принадлежит позиция: в общей выдаче поиска по
	// нему видно, откуда блюдо, и из него собирается заказ.
	RestaurantID uuid.UUID
	// Name — название товара, как его видит покупатель.
	Name string
	// Description — описание товара; пустое означает, что заведение его не дало.
	Description string
	// Price — цена товара в копейках.
	Price Money
	// IsAvailable — ложь означает стоп-лист заведения: товар виден, но заказать его нельзя.
	IsAvailable bool
}

// ErrProductNotFound — товара на витрине нет: он либо не существует, либо принадлежит
// заведению, которое больше не работает. Как и с заведением, случаи неразличимы
// намеренно — заказать такой товар всё равно нельзя.
var ErrProductNotFound = errors.New("product not found")
