package domain

import (
	"fmt"

	"github.com/google/uuid"
)

// RefusalReason — машиночитаемая причина, по которой заказ не принят заведением.
//
// Значения совпадают с кодами партнёрского контракта и клиентской спецификации: перечень
// там закрыт с обеих сторон, и заводить между ними третий словарь означало бы переводить
// одно в другое дважды — а расходиться они начали бы с первой же правки одного из них.
type RefusalReason string

const (
	// OutOfStock — позиции нет в наличии: она в стоп-листе заведения либо её осталось
	// меньше, чем заказали. Заведение эти случаи не различает, и площадке они одинаковы:
	// заказать позицию сейчас нельзя.
	OutOfStock RefusalReason = "out_of_stock"
	// PriceChanged — цена заведения отличается от той, которую площадка показала
	// покупателю. Актуальная цена приходит вместе с отказом.
	PriceChanged RefusalReason = "price_changed"
	// UnknownProduct — заведение не знает позицию, которую площадка показывала на
	// витрине: каталог отстал от меню.
	UnknownProduct RefusalReason = "unknown_product"
	// RestaurantClosed — заведение сейчас не работает и заказов не принимает.
	RestaurantClosed RefusalReason = "restaurant_closed"
)

// OrderRefusedError — заведение не берётся за заказ, и вот почему.
//
// Причина машиночитаемая: по ней покупатель выбирает, что делать дальше, — заменить
// кончившуюся позицию, согласиться на новую цену или уйти в другое заведение, — и
// выбирает программно, а не разбором текста. Текст `Detail` предназначен человеку и
// меняется без изменения версии поверхности.
type OrderRefusedError struct {
	// Reason — машиночитаемая причина отказа.
	Reason RefusalReason
	// ProductID — товар площадки, из-за которого отказан заказ; у отказа закрытого
	// заведения его нет, потому что дело не в позиции.
	ProductID uuid.UUID
	// CurrentPrice — актуальная цена товара по данным заведения; заполнена при причине
	// PriceChanged.
	CurrentPrice Money
	// Detail — пояснение для человека.
	Detail string
}

// Error возвращает причину, по которой заведение не приняло заказ.
func (e OrderRefusedError) Error() string {
	if e.ProductID == uuid.Nil {
		return fmt.Sprintf("заказ не принят заведением (%s): %s", e.Reason, e.Detail)
	}

	return fmt.Sprintf("заказ не принят заведением (%s), товар %s: %s", e.Reason, e.ProductID, e.Detail)
}
