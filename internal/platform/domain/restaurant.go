// Package domain — предметная область площадки: сущности, значения и правила, которые не
// зависят ни от хранилища, ни от транспорта.
package domain

import (
	"errors"

	"github.com/google/uuid"
)

// Restaurant — заведение на площадке. В витрине покупателя заведение — это место, куда
// можно сделать заказ: реквизиты интеграции и состояние синхронизации к нему относятся,
// но покупателю не показываются, поэтому здесь их нет.
type Restaurant struct {
	// ID — идентификатор заведения, по которому открывается карточка и заказывается меню.
	ID uuid.UUID
	// Name — название заведения, как его видит покупатель.
	Name string
}

// ErrRestaurantNotFound — заведения на площадке нет либо оно не работает. Одна ошибка на
// оба случая намеренно: покупателю неработающее заведение неотличимо от несуществующего —
// заказать в нём всё равно нельзя, а знание о том, что заведение когда-то было, ему
// ничего не даёт.
var ErrRestaurantNotFound = errors.New("restaurant not found")
