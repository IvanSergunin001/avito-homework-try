-- Меню заведений на витрине площадки. Позиция принадлежит заведению, но не исчезает
-- вместе с записью о нём: внешний ключ запрещающий, и заведение с меню база удалить не
-- даст. Каскад здесь стоил бы дороже, чем помогает — ручки удаления заведения в API нет
-- вовсе, поэтому `DELETE FROM platform.restaurants` бывает только у человека с psql в
-- руках, а там ошибка в условии не должна уносить чужое меню молча. Заведение, которое
-- больше не работает, отключают флагом `is_active`: оно пропадает с витрины, а меню
-- остаётся на месте и возвращается вместе с ним. Ключ внутри одной схемы границу
-- контекстов не нарушает — таблица заведения лежит рядом, в `platform`.
--
-- Цена — целое число копеек: числа с плавающей точкой для денег непригодны (`0.1 + 0.2`
-- не равно `0.3`), а `numeric` в Go всё равно вырождается в строку или float.
--
-- Признак `is_available` — стоп-лист заведения: товар остаётся на витрине, но заказать его
-- нельзя. Убирать позицию из выдачи вместо этого нельзя: покупатель искал бы блюдо,
-- которое вчера видел, и не находил его без объяснения.
--
-- «Нет описания» — это пустая строка, а не NULL: третье состояние у текста, который
-- показывается как есть, ничего не добавляет, а различать его пришлось бы всем читателям.

-- +goose Up
CREATE TABLE platform.products (
    id            uuid        PRIMARY KEY,
    restaurant_id uuid        NOT NULL REFERENCES platform.restaurants (id) ON DELETE RESTRICT,
    name          text        NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    description   text        NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
    price         bigint      NOT NULL CHECK (price >= 0),
    is_available  boolean     NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- Индекс повторяет запрос меню целиком: отбор по заведению и порядок, в котором страница
-- отдаётся клиенту. Без второго ключа в порядке позиции с одинаковым названием
-- переставлялись бы между запросами, и одна и та же попадала бы то на границу страницы
-- дважды, то никуда.
CREATE INDEX products_menu_idx ON platform.products (restaurant_id, name, id);

-- Поиск по названию — подстрочный (`ILIKE '%…%'`), а такому условию обычный B-tree не
-- помогает ничем: подстрока может начинаться где угодно. Триграммный индекс отбирает
-- кандидатов по трёхбуквенным кускам названия и превращает перебор всего каталога в
-- чтение короткого списка.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX products_name_trgm_idx ON platform.products USING gin (name gin_trgm_ops);

-- +goose Down
-- Расширение откатом не снимается: оно общее на всю базу, и одна таблица не вправе
-- решать за остальных, что оно больше не нужно.
DROP TABLE platform.products;
