-- Реквизиты интеграции заведения: по какому адресу площадка к нему стучится и по какому
-- хешу узнаёт его звонки. До этой миграции завести заведение было нечем — витрина только
-- читала таблицу, — поэтому колонки добавляются сразу NOT NULL и без значений по
-- умолчанию: пустой адрес интеграции означал бы заведение, до которого нельзя дойти.
--
-- Адрес хранится данными, а не выводится из названия и не лежит в конфигурации площадки:
-- переезд заведения на другой хост или порт — правка одной строки в базе, а не выпуск
-- новой версии службы.
--
-- Хранится хеш ключа, а не сам ключ: открытый ключ есть только у заведения, и утёкшая
-- копия базы не даёт возможности звонить от его имени. Хеш — SHA-256 в шестнадцатеричной
-- записи, отсюда ровно 64 знака; заведение ищется по нему поиском, поэтому он
-- детерминированный и без соли (почему так — в `internal/platform/domain/partner.go`).
--
-- Времени последней синхронизации каталога здесь нет: колонку заводит тот же слайс,
-- который эту синхронизацию делает, — иначе она стояла бы пустой и врала бы, что
-- каталог не обновлялся ни разу.

-- +goose Up
ALTER TABLE platform.restaurants
    ADD COLUMN base_url     text NOT NULL CHECK (length(base_url) BETWEEN 1 AND 500),
    ADD COLUMN api_key_hash text NOT NULL CHECK (length(api_key_hash) = 64);

-- Уникальность ключа — не только защита от коллизии (у 130 бит случайности её не
-- случится), но и индекс, которым идёт опознание звонящего: он выполняется на каждом
-- партнёрском запросе.
CREATE UNIQUE INDEX restaurants_api_key_hash_idx ON platform.restaurants (api_key_hash);

