-- Заказы покупателей площадки.
--
-- Идентификатор заказа выдаёт клиент (uuid v7) и присылает в теле запроса — он же
-- первичный ключ. Клиентский ключ выбран не ради экономии round-trip'а, а ради
-- идемпотентности: повторная отправка того же заказа обязана попасть в ту же строку, а не
-- завести вторую. Именно v7, а не v4: монотонный ключ ложится в конец индекса, тогда как
-- случайный разносит вставки по всему дереву.
--
-- `customer_id` — покупатель из заголовка `User-Id`. Внешнего ключа у него нет и таблицы
-- покупателей тоже: идентификатор приходит снаружи и ничем не подтверждён, а таблица,
-- которая заводится по первому же присланному значению, не даёт никаких гарантий —
-- она лишь делает вид, что покупатель зарегистрирован.
--
-- Позиции лежат в jsonb внутри заказа: заказ — агрегат, позиции не имеют самостоятельной
-- жизни и всегда читаются вместе с ним, а название и цена хранятся снимком — обновление
-- каталога не должно переписывать историю покупателя задним числом. Плата за это —
-- неудобные `GROUP BY` для аналитики; аналитика живёт не в OLTP, а обратный путь к
-- нормализованной таблице делается одним `SELECT` с `INSERT`.
--
-- Сумма — целое число копеек, как и цена товара: числа с плавающей точкой для денег
-- непригодны (`0.1 + 0.2` не равно `0.3`). Считает её площадка по своему каталогу;
-- присланной клиентом сумме здесь взяться неоткуда — колонка заполняется расчётом.

-- +goose Up
CREATE TABLE platform.orders (
    id            uuid        PRIMARY KEY,
    customer_id   uuid        NOT NULL,
    -- Заведение удаляется вместе со своими заказами только в том случае, если удалять
    -- его вообще позволено: ключ без каскада, поэтому заведение с историей заказов
    -- удалить не выйдет — оно отключается, а не стирается.
    restaurant_id uuid        NOT NULL REFERENCES platform.restaurants (id),
    -- Перечень статусов — весь жизненный путь заказа: матрица переходов живёт в агрегате
    -- с самого начала, и ограничение повторяет её словарь целиком, а не по частям.
    status        text        NOT NULL CHECK (status IN (
                                  'pending', 'under_review', 'confirmed',
                                  'cooking', 'delivering', 'completed', 'cancelled')),
    address       text        NOT NULL CHECK (length(address) BETWEEN 1 AND 500),
    items         jsonb       NOT NULL CHECK (jsonb_array_length(items) BETWEEN 1 AND 100),
    total         bigint      NOT NULL CHECK (total >= 0),
    -- «Заказ не отменён» — это пустая строка, а не NULL: третье состояние у значения,
    -- которое читается вместе со статусом, ничего не добавляет — отменён заказ или нет,
    -- видно по самому статусу.
    cancelled_by        text  NOT NULL DEFAULT '' CHECK (cancelled_by IN ('', 'customer', 'restaurant', 'support')),
    cancellation_reason text  NOT NULL DEFAULT '' CHECK (length(cancellation_reason) <= 500),
    created_at    timestamptz NOT NULL,
    updated_at    timestamptz NOT NULL
);

