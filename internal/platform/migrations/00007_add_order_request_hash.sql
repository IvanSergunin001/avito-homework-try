-- Отпечаток запроса, которым оформлен заказ: по нему повтор отличается от
-- переиспользования идентификатора заказа под другой заказ.
--
-- Ключ идемпотентности — сам идентификатор заказа, то есть первичный ключ этой таблицы:
-- отдельной таблицы ключей нет и не будет. Но одного ключа мало. Повтор нажатия
-- «Заказать» и ретрай по таймауту приходят с тем же идентификатором и тем же составом —
-- им площадка обязана отдать уже созданный заказ; сломанный клиент приходит с тем же
-- идентификатором и другой корзиной — ему площадка обязана отказать, потому что молча
-- отданный чужой по смыслу заказ означал бы подтверждение покупки, которой он не делал.
-- Различить эти два случая можно только сверив, чем заказ оформляли, — отпечаток и есть
-- эта сверка, свёрнутая в одну колонку.
--
-- Хеш, а не копия запроса: состав заказа уже лежит в `items`, и вторая его копия
-- разошлась бы с первой при первой же правке формата хранения. Считает отпечаток
-- предметная область (см. `internal/platform/domain/idempotency.go`), поэтому база о его
-- устройстве ничего не знает и длину его не проверяет: смена алгоритма не должна быть
-- миграцией схемы.
--
-- Значение по умолчанию нужно только существующим строкам — заказам, оформленным до этой
-- миграции: отпечатка у них взяться неоткуда. Пустой отпечаток не совпадёт ни с одним
-- настоящим, поэтому повтор такого заказа получит отказ «ключ переиспользован» вместо
-- самого заказа — это честнее, чем отдать заказ, о составе которого площадка судить не
-- может. Дальше умолчание снимается: заказ, записанный без отпечатка, был бы заказом,
-- который нельзя повторить.

