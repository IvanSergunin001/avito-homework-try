-- Журнал состояний заказа: во что заказ переходил, по чьему требованию и когда.
--
-- Статус в самой строке заказа отвечает только на вопрос «что с ним сейчас». История в
-- нём не хранится и восстановлению не подлежит: переход переписывает колонку и не
-- оставляет следа. А спрашивают у заказа как раз историю — сколько заведение думало над
-- заказом, когда именно он был отменён и кто этого потребовал, доехало ли уведомление
-- заведения или потерялось по дороге.
--
-- Запись сюда идёт в одной транзакции с изменением самого заказа: журнал, который пишется
-- отдельным запросом, при первом же сбое разойдётся с заказом — и разбирать придётся уже
-- не жалобу покупателя, а расхождение двух таблиц.
--
-- Таблица только дописывается: у записанного события нет ни правки, ни удаления. Поэтому
-- у неё нет и `updated_at` — событие не меняется, — а ключ выдаёт сама база
-- последовательностью: события одного заказа попадают в журнал по порядку, и порядок
-- ключа и есть порядок истории. uuid v7 здесь не нужен: снаружи на событие никто не
-- ссылается, идентификатор не показывается и не приходит в запросе.
--
-- `occurred_at` — часы площадки, даже когда о переходе сообщило заведение своим
-- уведомлением. Часы двух организаций не сверены, и журнал, собранный из двух источников
-- времени, перестал бы отвечать на единственный вопрос, ради которого ведётся: что за чем
-- случилось.

-- +goose Up
CREATE TABLE platform.order_status_events (
    id          bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- Ключ без каскада: заказы не удаляются, а журнал, который уезжает вместе с заказом,
    -- не ответил бы на вопрос, что с этим заказом было.
    order_id    uuid        NOT NULL REFERENCES platform.orders (id),
    -- Перечень повторяет словарь матрицы переходов целиком — тот же, что и у самого
    -- заказа: в журнал попадает то же состояние, в которое заказ перешёл.
    status      text        NOT NULL CHECK (status IN (
                                'pending', 'under_review', 'confirmed',
                                'cooking', 'delivering', 'completed', 'cancelled')),
    -- Инициатор — часть правила перехода, а не пометка: один и тот же переход одному
    -- разрешён, другому нет, и журнал без инициатора не отвечает на вопрос, кто двинул
    -- заказ. Пустого значения здесь нет: перехода без требующего не бывает.
    actor       text        NOT NULL CHECK (actor IN ('customer', 'restaurant', 'support')),
    occurred_at timestamptz NOT NULL
);

-- История одного заказа читается целиком и по порядку — этим индексом. Порядок задаёт
-- ключ, а не время: два перехода в одну микросекунду время не различает, а ключ различает.
CREATE INDEX order_status_events_order_idx ON platform.order_status_events (order_id, id);

