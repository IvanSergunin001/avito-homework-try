// Package migrations хранит миграции схемы площадки.
//
// В пакете нет ничего, кроме SQL-файлов и встроенной копии: инструмент миграций сюда
// не импортируется, и службы его не тянут. Миграции накатываются отдельным шагом запуска
// (сервис `migrate` в `compose.yaml`), а не бинарём службы на старте.
package migrations

import "embed"

// FS — встроенная копия миграций схемы. Шаг запуска накатывает эти же файлы с диска
// goose CLI, а тестовая оснастка (`internal/pkg/testdb`) — из этой копии: тесты не должны
// зависеть от того, из какого каталога их запустили.
//
//go:embed *.sql
var FS embed.FS

// SeedFS — демонстрационные данные: отдельный набор миграций со своим журналом.
//
// Отдельный он не ради красоты каталога. Демо-данные — часть запуска демо, а не часть
// схемы: тестам они не нужны, а мешают — каждый тест, который считает заведения, считал
// бы вместе со своими ещё и чужое, и правило предметной области в нём читалось бы через
// поправку на демо. Поэтому оснастка тестов накатывает только FS, а этот набор
// накатывается шагом запуска рядом со схемой.
//
//go:embed seed/*.sql
var SeedFS embed.FS

// SeedDir — каталог демонстрационных данных внутри SeedFS: goose нужен именно он, а не
// корень встроенной файловой системы.
const SeedDir = "seed"

const (
	// VersionTable — журнал применённых миграций схемы площадки.
	//
	// Он лежит в `public`, а не в самой схеме: goose создаёт журнал до того, как выполнит
	// первую миграцию, а первая миграция как раз и создаёт схему. Имя контекста в названии
	// таблицы нужно потому, что в одном инстансе живут независимые наборы миграций.
	VersionTable = "public.goose_platform_version"
	// SeedVersionTable — журнал применённых демонстрационных данных. Свой, а не общий со
	// схемой: наборы накатываются по отдельности, и общий журнал не дал бы накатить схему
	// без демо-данных.
	SeedVersionTable = "public.goose_platform_seed_version"
)
