// Package migrations хранит миграции схемы площадки.
//
// В пакете нет ничего, кроме SQL-файлов и встроенной копии: инструмент миграций сюда
// не импортируется, и службы его не тянут. Миграции накатываются отдельным шагом запуска
// (сервис `migrate` в `compose.yaml`), а не бинарём службы на старте.
package migrations

import "embed"

// FS — встроенная копия миграций схемы. Шаг запуска накатывает эти же файлы с диска
// goose CLI, а тестовая оснастка (`internal/pkg/testdb`) — из этой копии: тесты не должны
// зависеть от того, из какого каталога их запустили.
//
//go:embed *.sql
var FS embed.FS

// VersionTable — журнал применённых миграций схемы площадки.
//
// Он лежит в `public`, а не в самой схеме: goose создаёт журнал до того, как выполнит
// первую миграцию, а первая миграция как раз и создаёт схему. Имя контекста в названии
// таблицы нужно потому, что в одном инстансе живут два независимых набора миграций.
