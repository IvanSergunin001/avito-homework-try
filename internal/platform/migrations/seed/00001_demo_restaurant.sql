-- Демонстрационное заведение: та самая коробка, которая поднимается рядом с площадкой в
-- `compose.yaml`. Без него площадка после `docker compose up` пуста, и первый же взгляд на
-- витрину показывает не работающую систему, а пустой список.
--
-- Заведение заводится seed-миграцией, а не кодом службы на старте: служба, дописывающая
-- себе данные при каждом запуске, рано или поздно перезаписывает то, что администратор
-- поправил руками. Миграция выполняется один раз, а дальше заведение живёт как обычное —
-- его адрес меняется админской ручкой.
--
-- Ключ демо-заведения известен всем и годится только для демонстрации:
--
--     pk_DEMOKEYDEMOKEYDEMOKEYDEMOK
--
-- В базу он, как и всякий партнёрский ключ, попадает хешем — хеш здесь и считается, из
-- самого ключа, чтобы связь между напечатанным ключом и хранимым хешем была видна и
-- проверяема, а не держалась на честном слове.
--
-- Адрес — имя службы коробки в сети Compose и её порт по умолчанию. Порт коробки
-- настраивается переменной окружения, и если его сменили, адрес заведения правится
-- админской ручкой: ради этого он и живёт данными.

-- +goose Up
INSERT INTO platform.restaurants (id, name, base_url, api_key_hash, is_active)
VALUES (
    '018f2b5c-1f4a-7c3e-9a10-2b8f5d7c1a01',
    'Пекарня «Батон»',
    'http://restaurant:8081',
    encode(sha256(convert_to('pk_DEMOKEYDEMOKEYDEMOKEYDEMOK', 'UTF8')), 'hex'),
    true
);

-- +goose Down
-- Меню сносится первым, хотя сид его и не заводил: товары демо-заведению пишет
-- синхронизация каталога с коробки, и после любого показа они там есть. Заведение с меню
-- база удалить не даст: внешний ключ товара запрещающий (см. 00003_create_products.sql).
-- Без этой строки откат упирался бы в ограничение ровно после того прогона, ради которого
-- демо-заведение и заведено.
DELETE FROM platform.products WHERE restaurant_id = '018f2b5c-1f4a-7c3e-9a10-2b8f5d7c1a01';
-- Заказы демо-заведения этот откат не трогает, и на них он споткнётся: у
-- `platform.orders.restaurant_id` внешний ключ тоже запрещающий (см. 00006_create_orders.sql),
-- поэтому база не даст удалить заведение, по которому оформлен хоть один заказ. Пока заказы
-- заводятся только руками, до этого не доходит, но `migrate reset` на базе, где ими уже
-- пользовались, упадёт. Лечится строкой `DELETE FROM platform.orders WHERE restaurant_id = ...`
-- перед удалением заведения; здесь её нет намеренно — находка ревью PR #25, отдельного решения
-- по ней пока нет, и молча расширять снос сида на чужие заказы неправильно.
DELETE FROM platform.restaurants WHERE id = '018f2b5c-1f4a-7c3e-9a10-2b8f5d7c1a01';
