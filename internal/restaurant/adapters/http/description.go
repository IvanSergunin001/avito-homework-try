package http

// Описание позиции — единственное необязательное поле обеих проекций меню, и обе стороны
// перевода живут здесь: наружу его либо нет вовсе, либо оно непустое, внутри — просто
// строка. Помощники общие для рабочего места и партнёрского контракта: правило одно, и
// вторая его копия разошлась бы с первой первой же правкой.

// optional отдаёт адрес описания или nil, если описания нет: пустая строка в ответе
// сообщила бы, что описание есть и оно пустое.
func optional(description string) *string {
	if description == "" {
		return nil
	}

	return &description
}

// orEmpty приводит описание из тела запроса к строке: его могли не прислать вовсе, и
// «нет описания» и «описание пустое» — для позиции меню одно и то же.
func orEmpty(description *string) string {
	if description == nil {
		return ""
	}

	return *description
}
