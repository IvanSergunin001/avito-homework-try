// Package domain — предметная область коробки заведения: сущности, значения и правила,
// которые не зависят ни от хранилища, ни от транспорта.
package domain

import (
	"errors"
	"fmt"
	"strings"
	"unicode/utf8"

	"github.com/google/uuid"
)

const (
	// nameMaxLength и descriptionMaxLength — пределы длины, объявленные в спецификациях
	// коробки. Считаем их в знаках, а не в байтах: в названиях кириллица, и байтовый
	// предел обрезал бы русское название вдвое раньше обещанного.
	nameMaxLength        = 200
	descriptionMaxLength = 2000

	// stockMax — потолок остатка, объявленный в спецификациях коробки. Он есть не ради
	// здравого смысла, а ради честного отказа: колонка хранит остаток 32-битным целым, и
	// число больше него база не примет — оператор получил бы «повторите запрос позже» на
	// опечатку, которая верной не станет никогда.
	stockMax = 1_000_000
)

// Money — сумма в минорных единицах валюты, то есть в копейках. Отдельный тип, а не
// просто число: единица измерения видна в подписи и не теряется при передаче, а сложить
// копейки с остатком по недосмотру нельзя.
//
// Целое, а не число с плавающей точкой: `0.1 + 0.2` в двоичной дроби не равно `0.3`, и
// деньги, посчитанные так, расходятся с чеком.
type Money int64

// Stock — остаток позиции в штуках: сколько её сейчас можно продать.
type Stock int

// MenuCard — то, что заведение рассказывает о позиции: название, описание и цена.
// Остаток и стоп-лист сюда не входят — карточку правят обдуманно и редко, а остаток и
// отметку «закончилось» оператор меняет в течение дня.
type MenuCard struct {
	// Name — название позиции, как его увидит покупатель на витрине площадки.
	Name string
	// Description — описание позиции; пустое означает, что заведение его не дало.
	Description string
	// Price — цена позиции в копейках.
	Price Money
}

// MenuItem — позиция меню коробки: карточка, остаток и отметка стоп-листа.
//
// Доступность отдельным полем не хранится: она следует из остатка и отметки, и хранить
// её значило бы держать в базе третий источник правды, который рано или поздно разойдётся
// с двумя первыми.
type MenuItem struct {
	// ID — идентификатор позиции в коробке. Он же уезжает площадке внешним
	// идентификатором позиции: коробка для площадки — обычное заведение со своей системой.
	ID uuid.UUID
	// MenuCard — карточка позиции.
	MenuCard
	// Stock — остаток позиции.
	Stock Stock
	// InStopList — оператор отметил, что позиции сейчас нет.
	InStopList bool
}

// NewMenuCard собирает карточку позиции, проверяя то, что о ней рассказали.
//
// Проверка живёт в предметной области, а не в обработчике: пределы объявлены в
// спецификации, но кодогенератор их не сверяет, а правило «у позиции есть название и
// неотрицательная цена» одинаково верно, откуда бы позиция ни пришла.
func NewMenuCard(name, description string, price Money) (MenuCard, error) {
	// Пробелы по краям — след ввода, а не часть названия: позиция «  » названия не имеет.
	name = strings.TrimSpace(name)

	switch {
	case utf8.RuneCountInString(name) < 1 || utf8.RuneCountInString(name) > nameMaxLength:
		return MenuCard{}, InvalidMenuItemError{
			Reason: fmt.Sprintf("название: от 1 до %d знаков", nameMaxLength),
		}
	case utf8.RuneCountInString(description) > descriptionMaxLength:
		return MenuCard{}, InvalidMenuItemError{
			Reason: fmt.Sprintf("описание: не длиннее %d знаков", descriptionMaxLength),
		}
	case price < 0:
		return MenuCard{}, InvalidMenuItemError{Reason: "цена: не может быть отрицательной"}
	}

	return MenuCard{Name: name, Description: description, Price: price}, nil
}

// NewStock проверяет остаток: отрицательного остатка не бывает — «отсутствие» позиции
// выражается нулём и стоп-листом, а не долгом перед покупателем, — а сверху он ограничен
// тем, что коробка в состоянии сохранить.
func NewStock(count int) (Stock, error) {
	if count < 0 || count > stockMax {
		return 0, InvalidMenuItemError{
			Reason: fmt.Sprintf("остаток: от 0 до %d", stockMax),
		}
	}

	return Stock(count), nil
}

// IsAvailable отвечает на единственный вопрос площадки о позиции: можно ли её заказать
// прямо сейчас.
//
// Причин недоступности две, и площадке их не различают: оператор отметил позицию в
// стоп-листе или она кончилась. Покупателю в обоих случаях нужно одно и то же — не
// пытаться её заказать, а из меню позиция не исчезает, иначе он искал бы блюдо, которое
// вчера видел, и не находил его без объяснения.
func (i MenuItem) IsAvailable() bool {
	return !i.InStopList && i.Stock > 0
}

// ExternalID — идентификатор позиции в системе заведения, каким его видит площадка.
//
// Отдельного поля под него нет: площадка обновляет каталог по паре «заведение + внешний
// идентификатор», и требование к нему одно — быть стабильным во времени. Собственный
// идентификатор позиции этому требованию отвечает и не даёт оператору завести две
// позиции с одним внешним идентификатором.
func (i MenuItem) ExternalID() string {
	return i.ID.String()
}

// ErrMenuItemNotFound — позиции с таким идентификатором в меню нет.
var ErrMenuItemNotFound = errors.New("menu item not found")

// InvalidMenuItemError — позицию описали так, что завести её в меню нельзя. Причина —
// текстом: её читает оператор, который видит форму и в состоянии её исправить, поэтому
// машиночитаемой ветки поведения у неё нет.
type InvalidMenuItemError struct {
	// Reason — что именно не так, словами для оператора.
	Reason string
}

// Error возвращает причину отказа.
func (e InvalidMenuItemError) Error() string {
	return e.Reason
}
