// Уведомление площадки о смене статуса заказа.
//
// Площадка статусы не опрашивает: инициатива у той стороны, которая знает, что
// происходит с заказом на кухне. Значит, доставить уведомление — обязанность коробки, и
// обязанность эта переживает то, что площадка минуту не отвечала: заказ уже готовится, а
// покупатель по-прежнему видит «принят».
//
// Отсюда очередь в собственной базе коробки, а не вызов площадки прямо из обработчика.
// Смена статуса и уведомление о ней записываются одной транзакцией: иначе оператор,
// нажавший «в доставку» в момент недоступности площадки, получил бы либо ошибку на
// заказ, который на кухне уже уехал, либо молча потерянный статус. Что уведомление
// уехало — видно в самой очереди, и разбирать «почему у покупателя старый статус» можно
// по данным, а не по логам чужой системы.

package domain

import (
	"fmt"
	"time"

	"github.com/google/uuid"
)

// PendingNotification — уведомление, которое коробка ещё должна доставить площадке.
//
// Заказ назван обоими идентификаторами не для удобства: `OrderID` — это строка очереди
// коробки, а адресуется уведомление тем идентификатором, которым заказ знает площадка.
type PendingNotification struct {
	// OrderID — заказ коробки, чей статус сменился.
	OrderID uuid.UUID
	// PlatformOrderID — тот же заказ на площадке: ей уведомление и адресовано.
	PlatformOrderID uuid.UUID
	// Status — состояние, в которое заказ перешёл.
	Status OrderStatus
	// Reason — почему заказ отменён; у остальных уведомлений пуста.
	Reason string
	// OccurredAt — когда коробка записала смену статуса.
	OccurredAt time.Time
	// Attempts — сколько попыток доставки уже сделано и не удалось.
	Attempts int
}

// RetryPolicy — как коробка повторяет недоставленное уведомление.
//
// Повтор нужен потому, что недоступность площадки — обычное дело: перезапуск, обрыв
// сети, секунда перегрузки. Откладывание растёт, чтобы коробка не добивала лежащую
// площадку с той же частотой, с какой ходила к живой; число попыток ограничено, чтобы
// очередь не наполнялась вечными уведомлениями, которые никто не читает. Исчерпание
// попыток — это не «доставили», а повод разбираться руками, и потому оно остаётся
// видимым и в данных, и в логах.
type RetryPolicy struct {
	// maxAttempts — сколько попыток доставки коробка делает, прежде чем сдаться.
	maxAttempts int
	// baseDelay — пауза перед первым повтором; каждая следующая вдвое длиннее.
	baseDelay time.Duration
}

// maxRetryDelay — потолок паузы между попытками.
//
// Удвоение без потолка при щедро заданном числе попыток уводит следующую попытку в
// послезавтра, а то и переполняет длительность. Статус, доехавший через пять минут, уже
// опоздал; статус, доехавший через сутки, не нужен вовсе.
const maxRetryDelay = 5 * time.Minute

// NewRetryPolicy собирает правило повторов: сколько попыток и с какой первой паузой.
//
// Обе величины приходят из конфигурации, а не из констант: сколько раз стучаться в
// соседнюю систему и как долго ждать — это решение эксплуатации, а не предметной области.
// Значения вне смысла отвергаются здесь, а не подправляются молча: коробка, поднятая с
// нулём попыток, не уведомляла бы площадку вовсе, а узналось бы это от покупателя.
func NewRetryPolicy(maxAttempts int, baseDelay time.Duration) (RetryPolicy, error) {
	switch {
	case maxAttempts < 1:
		return RetryPolicy{}, fmt.Errorf("число попыток доставки: %d, ожидали хотя бы одну", maxAttempts)
	case baseDelay <= 0:
		return RetryPolicy{}, fmt.Errorf("пауза перед повтором: %s, ожидали больше нуля", baseDelay)
	}

	return RetryPolicy{maxAttempts: maxAttempts, baseDelay: baseDelay}, nil
}

// NextAttempt отвечает, когда повторять доставку после attempts неудачных попыток.
//
// Второй результат ложен, когда попытки исчерпаны: повторять больше нечего, и уведомление
// остаётся в очереди недоставленным — со счётчиком попыток, по которому видно, что его
// не забыли, а не смогли доставить.
func (p RetryPolicy) NextAttempt(attempts int) (time.Duration, bool) {
	switch {
	case attempts >= p.maxAttempts:
		return 0, false
	case attempts < 1:
		// По уведомлению ещё не пробовали: ждать ему нечего.
		return 0, true
	}

	// Пауза удваивается с каждой неудачей: 1-я, 2-я, 4-я минута вместо трёх подряд.
	// Считаем сдвигом по числу уже сделанных попыток, а не возведением в степень:
	// показатель здесь целый и небольшой, а потолок обрезает всё, что успело вырасти.
	delay := p.baseDelay << (attempts - 1)
	if delay <= 0 || delay > maxRetryDelay {
		return maxRetryDelay, true
	}

	return delay, true
}

// MaxAttempts — сколько попыток доставки коробка делает всего.
func (p RetryPolicy) MaxAttempts() int {
	return p.maxAttempts
}
