-- Меню коробки: то, что ведёт оператор заведения без своих систем, и то, что коробка
-- отдаёт площадке по партнёрскому контракту. Таблица одна на обе поверхности: меню у
-- заведения одно, и расхождение между тем, что видит оператор, и тем, что уезжает
-- площадке, было бы дефектом, а не свойством.
--
-- Цена — целое число копеек: числа с плавающей точкой для денег непригодны (`0.1 + 0.2`
-- не равно `0.3`), а `numeric` в Go всё равно вырождается в строку или float.
--
-- Доступность позиции колонкой не хранится, хотя в `docs/PLAN.md` схема набросана с
-- `is_available`: доступность складывается из двух вещей, которыми оператор управляет
-- по отдельности, — отметки стоп-листа и остатка, — и третья колонка была бы третьим
-- источником правды, который рано или поздно разойдётся с двумя первыми. Наружу, в
-- партнёрскую выдачу, доступность считается: нет отметки и остаток больше нуля.
--
-- Внешнего идентификатора позиции отдельной колонкой тоже нет: площадка обновляет каталог
-- по паре «заведение + внешний идентификатор», и требование к нему одно — быть стабильным
-- во времени. Первичный ключ этому отвечает и вдобавок не даёт завести две позиции с
-- одним внешним идентификатором.
--
-- «Нет описания» — это пустая строка, а не NULL: третье состояние у текста, который
-- показывается как есть, ничего не добавляет, а различать его пришлось бы всем читателям.

-- +goose Up
CREATE TABLE restaurant.menu_items (
    id           uuid        PRIMARY KEY,
    name         text        NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    description  text        NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
    price        bigint      NOT NULL CHECK (price >= 0),
    stock        integer     NOT NULL DEFAULT 0 CHECK (stock >= 0),
    in_stop_list boolean     NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- Индекс повторяет запрос страницы меню целиком — порядок, в котором она отдаётся и
-- оператору, и площадке. Без второго ключа в порядке позиции с одинаковым названием
-- переставлялись бы между запросами, и одна и та же попадала бы то на границу страницы
-- дважды, то никуда.
CREATE INDEX menu_items_page_idx ON restaurant.menu_items (name, id);

