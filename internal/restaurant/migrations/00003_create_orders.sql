-- Входящие заказы коробки: то, что площадка передала заведению по партнёрскому контракту,
-- и то, что разбирает оператор на своём рабочем месте.
--
-- Идентификаторов у заказа три, и каждый отвечает за своё. `id` — заказ коробки, её
-- собственный (uuid v7, монотонный: клиентский первичный ключ не разносит вставки по
-- индексу). `platform_order_id` — ссылка на тот же заказ у площадки: с ней приходят
-- разбираться, когда заказ вызывает вопросы. `idempotency_key` — то, по чему коробка
-- узнаёт повторную отправку; по контракту он совпадает с идентификатором заказа площадки,
-- но хранится отдельно, потому что обе величины даёт площадка и коробке не о чем судить,
-- если однажды они разойдутся.
--
-- Уникальность ключа идемпотентности — это и есть защита от второго заказа: повтор
-- отбивается ограничением базы, а не проверкой «нет ли уже такого» перед вставкой, между
-- которой и вставкой помещается вторая доставка того же заказа.
--
-- Позиции лежат в jsonb внутри заказа: заказ — агрегат, позиции не имеют самостоятельной
-- жизни и всегда читаются вместе с ним, а название и цена хранятся снимком — правка меню
-- не должна менять заказ задним числом. Плата за это — неудобные `GROUP BY` для
-- аналитики; аналитика живёт не в OLTP, а обратный путь к нормализованной таблице
-- делается одним `SELECT` с `INSERT`.
--
-- Сумма — целое число копеек, как и цена позиции меню: числа с плавающей точкой для денег
-- непригодны.

-- +goose Up
CREATE TABLE restaurant.orders (
    id                  uuid        PRIMARY KEY,
    platform_order_id   uuid        NOT NULL,
    idempotency_key     uuid        NOT NULL UNIQUE,
    -- Перечень статусов — тот, которым коробка живёт сейчас: заказ принят и ждёт решения
    -- оператора, подтверждён либо отклонён. Готовка, доставка и завершение появятся
    -- вместе с продвижением статусов оператором — и вместе с ними в этом ограничении.
    status              text        NOT NULL CHECK (status IN ('under_review', 'confirmed', 'cancelled')),
    address             text        NOT NULL CHECK (length(address) BETWEEN 1 AND 500),
    items               jsonb       NOT NULL CHECK (jsonb_array_length(items) BETWEEN 1 AND 100),
    total               bigint      NOT NULL CHECK (total >= 0),
    -- «Причины нет» — это пустая строка, а не NULL: третье состояние у текста, который
    -- показывается как есть, ничего не добавляет, а различать его пришлось бы всем читателям.
    cancellation_reason text        NOT NULL DEFAULT '' CHECK (length(cancellation_reason) <= 500),
    -- Время оформления заказа покупателем присылает площадка — и может не прислать:
    -- здесь NULL осмысленный, это «площадка не сказала», а не «заказ оформлен в эпоху».
    placed_at           timestamptz,
    accepted_at         timestamptz NOT NULL,
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Индекс повторяет запрос списка заказов целиком: оператор работает с началом списка, а
-- свежий заказ — это тот, который коробка приняла последним. Второй ключ в порядке нужен
-- по той же причине, что и в меню: без него заказы, принятые в одну миллисекунду,
-- переставлялись бы между страницами.
CREATE INDEX orders_page_idx ON restaurant.orders (accepted_at DESC, id DESC);

